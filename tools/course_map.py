"""Regenerate the course map in README.md (between the COURSE-MAP markers) from course/lectures.yaml,
and check that every study guide it links to exists.

    uv run tools/course_map.py          # rewrite README.md
    uv run tools/course_map.py --check  # exit 1 if README.md is out of date or a link is broken
"""

from __future__ import annotations

import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent
SPEC = yaml.safe_load((ROOT / "course" / "lectures.yaml").read_text(encoding="utf-8"))
VIDEOS = SPEC.get("videos_repo", "https://github.com/JunyiZhou-Conny/Explainer_Videos")
BEGIN, END = "<!-- COURSE-MAP:BEGIN (generated by tools/course_map.py; edit course/lectures.yaml) -->", "<!-- COURSE-MAP:END -->"


def repo_link(t: dict) -> str:
    if t.get("colab"):
        return f"[Colab]({t['colab']})"
    url = SPEC["repos"][t["repo"]]["url"]
    if t.get("branch"):
        url += f"/tree/{t['branch']}"
    label = t["repo"] + (f"@{t['branch']}" if t.get("branch") else "")
    return f"[`{label}`]({url})"


def video_cell(lec: dict) -> str:
    vid = lec.get("video")
    if not vid:
        return "—"
    status = lec.get("video_status", "planned")
    if status == "planned":
        return "planned"
    url = f"{VIDEOS}/tree/main/videos/{vid}"
    return f"[{status}]({url})"


def table() -> str:
    rows = ["| # | Lecture | Tutorials | Study guide | Video |", "| --: | --- | --- | --- | --- |"]
    for lec in SPEC["lectures"]:
        tuts = lec.get("tutorials") or []
        cells = "<br>".join(f"{t['name']} · {repo_link(t)}" for t in tuts) or (lec.get("note") or "no tutorial")
        guide = f"[guide]({lec['guide']})" if lec.get("guide") else "—"
        title = f"[{lec['title']}]({lec['ed']})"
        rows.append(f"| {lec['n']} | {title} | {cells} | {guide} | {video_cell(lec)} |")
    return "\n".join(rows)


def render(readme: str) -> str:
    a, b = readme.index(BEGIN) + len(BEGIN), readme.index(END)
    return readme[:a] + "\n" + table() + "\n" + readme[b:]


def main() -> int:
    path = ROOT / "README.md"
    old = path.read_text(encoding="utf-8")
    new = render(old)
    missing = [l["guide"] for l in SPEC["lectures"] if l.get("guide") and not (ROOT / l["guide"]).exists()]
    if "--check" in sys.argv:
        ok = new == old and not missing
        if new != old:
            print("README.md is out of date: run `uv run tools/course_map.py`")
        for m in missing:
            print(f"missing study guide: {m}")
        return 0 if ok else 1
    path.write_text(new, encoding="utf-8")
    for m in missing:
        print(f"note: study guide not written yet: {m}")
    print("README.md updated")
    return 0


if __name__ == "__main__":
    sys.exit(main())
